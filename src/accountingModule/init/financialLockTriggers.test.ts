import { beforeEach, describe, expect, it, vi } from 'vitest';
import KnexConnection from '../../database/KnexConnections';
import { ensureFinancialFinalizationTriggers, ensureFinancialRecordLockSourceRefIndex } from './accountingSchemaInit';
import { accountingSqlDatabase } from '../../testSupport/accountingSqlDatabase';

vi.mock('../../database/KnexConnections', () => ({ default: vi.fn() }));
const raw = vi.fn().mockResolvedValue(undefined);
beforeEach(() => {
     vi.clearAllMocks();
     vi.mocked(KnexConnection).mockResolvedValue({
          schema: { hasTable: async () => true }, raw,
     } as unknown as Awaited<ReturnType<typeof KnexConnection>>);
});
function sql(name: string) {
     const match = raw.mock.calls.map(([statement]) => String(statement))
          .find(statement => statement.startsWith(`CREATE TRIGGER ${name} `));
     if (!match) throw new Error(`Missing trigger ${name}`);
     return match;
}

describe('financial record lock source lookup index', () => {
     it('adds the index to existing tenant tables', async () => {
          const index = vi.fn();
          const alterTable = vi.fn(async (_table: string, callback: (builder: { index: typeof index }) => void) => {
               callback({ index });
          });
          const db = {
               raw: vi.fn().mockResolvedValue([[], []]),
               schema: { alterTable },
          } as unknown as Parameters<typeof ensureFinancialRecordLockSourceRefIndex>[0];

          await ensureFinancialRecordLockSourceRefIndex(db);

          expect(db.raw).toHaveBeenCalledWith('SHOW INDEX FROM ??', ['financial_record_locks']);
          expect(index).toHaveBeenCalledWith(
               ['source_table', 'source_ref'],
               'idx_fin_record_locks_source_ref',
          );
     });

     it('does not recreate an existing index with the expected definition', async () => {
          const alterTable = vi.fn();
          const db = {
               raw: vi.fn().mockResolvedValue([[
                    { Key_name: 'idx_fin_record_locks_source_ref', Column_name: 'source_table', Seq_in_index: 1, Non_unique: 1 },
                    { Key_name: 'idx_fin_record_locks_source_ref', Column_name: 'source_ref', Seq_in_index: 2, Non_unique: 1 },
               ], []]),
               schema: { alterTable },
          } as unknown as Parameters<typeof ensureFinancialRecordLockSourceRefIndex>[0];

          await ensureFinancialRecordLockSourceRefIndex(db);

          expect(alterTable).not.toHaveBeenCalled();
     });
});

describe('MySQL historical range protections generated by accounting bootstrap', () => {
     it.each(['billing', 'dboservices', 'billinghx', 'expensesrecord', 'expense_payments', 'finance_ledger',
          'receipts', 'dbobillingrefundtable', 'acc_journal_entries', 'acc_journal_lines',
          'acc_manual_journals', 'acc_manual_journal_lines', 'acc_cash_flow_classifications',
          'acc_subledger_entries', 'financial_day_closures'])('protects insert/update/delete of %s', async table => {
          await ensureFinancialFinalizationTriggers(17);
          const insert = sql(`trg_fin_lock_${table}_insert`);
          const update = sql(`trg_fin_lock_${table}_update`);
          const deletion = sql(`trg_fin_lock_${table}_delete`);
          expect(insert).toContain('financial_historical_locks');
          expect(insert).toContain('NEW.');
          expect(update).toContain('OLD.');
          expect(update).toContain('NEW.');
          expect(update.match(/FROM financial_historical_locks/g)).toHaveLength(2);
          expect(deletion).toContain('financial_historical_locks');
          expect(deletion).toContain('OLD.');
          for (const statement of [insert, update, deletion]) {
               expect(statement).toContain('BETWEEN start_date AND end_date FOR UPDATE');
               expect(statement).toContain("SIGNAL SQLSTATE '45000'");
          }
     });
     it('checks every branch of multi-branch journal headers and classifications', async () => {
          await ensureFinancialFinalizationTriggers(17);
          expect(sql('trg_fin_lock_acc_journal_entries_update')).toContain('branchid IN (SELECT branchid FROM acc_journal_lines WHERE journal_entry_id = OLD.id)');
          expect(sql('trg_fin_lock_acc_manual_journals_delete')).toContain('branchid IN (SELECT branchid FROM acc_manual_journal_lines WHERE manual_journal_id = OLD.id)');
          expect(sql('trg_fin_lock_acc_cash_flow_classifications_insert')).toContain('branchid IN (SELECT branchid FROM acc_journal_lines WHERE journal_entry_id = NEW.journal_entry_id)');
     });
     it('makes historical ranges append-only while retaining finalized closure protections', async () => {
          await ensureFinancialFinalizationTriggers(17);
          expect(sql('trg_fin_append_financial_historical_locks_update')).toContain('IMMUTABLE_AUDIT_RECORD');
          expect(sql('trg_fin_append_financial_historical_locks_delete')).toContain('IMMUTABLE_AUDIT_RECORD');
          expect(sql('trg_fin_closure_finalized_update')).toContain("OLD.status = 'finalized'");
          expect(sql('trg_fin_lock_billing_update')).toContain('financial_record_locks');
     });
     it('executes the generated billing predicates against legacy inserts, updates and deletes', async () => {
          await ensureFinancialFinalizationTriggers(17);
          const f = accountingSqlDatabase();
          try {
               f.native.exec(`
                 CREATE TABLE billing(billingid INTEGER PRIMARY KEY,branchid INTEGER,billedon TEXT);
                 CREATE TABLE financial_day_closures(branchid INTEGER,financial_date TEXT,status TEXT);
                 CREATE TABLE financial_record_locks(source_table TEXT,source_ref TEXT);
                 CREATE TABLE financial_historical_locks(branchid INTEGER,start_date TEXT,end_date TEXT);
                 INSERT INTO billing VALUES (1,2,'2024-01-01'),(2,2,'2026-11-04'),(3,3,'2024-01-01');
                 INSERT INTO financial_historical_locks VALUES (2,'2024-01-01','2025-12-31');
               `);
               for (const action of ['insert', 'update', 'delete']) {
                    // SQLite executes the same predicates; MySQL SIGNAL/locking grammar is checked above.
                    const statement = sql(`trg_fin_lock_billing_${action}`).replace(/ FOR UPDATE/g, '')
                         .replace(/BEGIN IF (.+) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '([^']+)'; END IF; END$/,
                              "WHEN $1 BEGIN SELECT RAISE(ABORT, '$2'); END");
                    f.native.exec(statement);
               }
               for (const mutation of [
                    "INSERT INTO billing VALUES (4,2,'2024-01-01')",
                    "UPDATE billing SET billedon='2026-11-04' WHERE billingid=1",
                    'UPDATE billing SET branchid=3 WHERE billingid=1',
                    "UPDATE billing SET billedon='2025-12-31' WHERE billingid=2",
                    'UPDATE billing SET branchid=2 WHERE billingid=3',
                    'DELETE FROM billing WHERE billingid=1',
               ]) expect(() => f.native.exec(mutation)).toThrow(/FINANCIAL_(?:RECORD|DAY)_FINALIZED/);
               f.native.exec("INSERT INTO billing VALUES (4,2,'2026-11-04'); UPDATE billing SET billedon='2024-02-01' WHERE billingid=3; DELETE FROM billing WHERE billingid=4;");
               expect(await f.db('billing').orderBy('billingid')).toEqual([
                    { billingid: 1, branchid: 2, billedon: '2024-01-01' },
                    { billingid: 2, branchid: 2, billedon: '2026-11-04' },
                    { billingid: 3, branchid: 3, billedon: '2024-02-01' },
               ]);
          } finally {
               await f.db.destroy();
          }
     });
});

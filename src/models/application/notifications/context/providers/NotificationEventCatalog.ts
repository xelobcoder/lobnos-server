const CATALOG_BY_CODE = new Map<string, EventCatalogEntry>();
for (const item of NOTIFICATION_EVENT_CATALOG) {
     CATALOG_BY_CODE.set(item.eventCode, item);
}

export function getEventCatalogEntry(eventCode: string): EventCatalogEntry | undefined {
     return CATALOG_BY_CODE.get(eventCode);
}

export function buildEventDefinitionFromCatalog(eventCode: string): EventDefinition | null {
     const entry = CATALOG_BY_CODE.get(eventCode);
     if (!entry) return null;

     let layoutKind: EventTemplateLayoutKind = 'enterprise';
     if (eventCode.startsWith('PURCHASE_ORDER_')) {
          layoutKind = (
               eventCode === 'PURCHASE_ORDER_RECEIVED'
               || eventCode === 'PURCHASE_ORDER_PARTIALLY_RECEIVED'
               || eventCode === 'PURCHASE_ORDER_ACKNOWLEDGED'
          )
               ? 'goods_received_invoice'
               : 'purchase_order_invoice';
     } else if (eventCode.startsWith('SUPPLIER_PAYMENT_')) {
          layoutKind = 'supplier_payment_invoice';
     }

     return makeDomainDefinition(
          eventCode,
          entry.variables,
          entry.requiredReferences,
          entry.title,
          entry.intro,
          entry.details,
          entry.actionText,
          entry.actionValue,
          layoutKind,
          entry.subject,
     );
}

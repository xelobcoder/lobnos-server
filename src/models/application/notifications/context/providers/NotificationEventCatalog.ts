export type EventCatalogEntry = {
     eventCode: string;
     module: string;
     provider: string;
     requiredReferences: Array<keyof EventReferenceMap>;
     variables: EventVariableDefinition[];
     subject: string;
     title: string;
     intro: string;
     details: string[];
     actionText?: string;
     actionValue?: string;
};

function entry(
     eventCode: string,
     module: string,
     provider: string,
     requiredReferences: Array<keyof EventReferenceMap>,
     variables: EventVariableDefinition[],
     subject: string,
     title: string,
     intro: string,
     details: string[],
     actionText?: string,
     actionValue?: string,
): EventCatalogEntry {
     return {
          eventCode,
          module,
          provider,
          requiredReferences,
          variables,
          subject,
          title,
          intro,
          details,
          actionText,
          actionValue,
     };
}

